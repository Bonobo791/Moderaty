</p>
<p>
	<strong>10.3</strong> YouTube / Google LLC acts as the source platform and, in respect of
	comment publication and moderation execution, as an independent platform operator under its
	own terms; the Parties' obligations regarding the YouTube API are limited to lawful retrieval
	and execution of moderation actions on the Controller's channel.
</p>

<h2 id="s11">11. International Data Transfers</h2>
<p>
	<strong>11.1</strong> The Parties acknowledge that Comment Data transits infrastructure
	located outside Brazil, including YouTube/Google systems and the sub-processors identified in
	Annex III.
</p>
<p>
	<strong>11.2</strong> Any international transfer of personal data under this DPA shall rely
	on a valid mechanism under Article 33 of the LGPD. Where the transfer mechanism is standard
	contractual clauses, the Parties incorporate the ANPD SCCs (Resolution CD/ANPD no 19/2024) as
	set out in Annex IV. Standard contractual clauses of other jurisdictions (including EU SCCs)
	shall not be used as a substitute for the ANPD SCCs.
</p>
<p>
	<strong>11.3</strong> The Processor shall maintain in Annex III a current record of the
	transfer mechanism relied upon for each sub-processor — including, for Turso, the specific
	edge-replica regions enabled at any time — and shall update it upon any change. The Processor
	shall not enable database replicas in regions not recorded in Annex III.
</p>

<h2 id="s12">12. Security Measures</h2>
<p>
	<strong>12.1</strong> The Processor shall implement and maintain the technical and
	organizational measures described in Annex II, including encryption in transit,
	least-privilege access control, credential and API-key management, and environment isolation.
</p>
<p>
	<strong>12.2</strong> The Processor shall regularly test, assess, and evaluate the
	effectiveness of those measures and shall adjust them to address material changes in risk.
</p>

<h2 id="s13">13. Data Subject Requests</h2>
<p>
	<strong>13.1</strong> Taking into account the data-minimization measures of Section 7 (which
	limit the personal data the Processor holds), the Processor shall provide reasonable
	assistance so
	the Controller can respond to data subject requests within the LGPD deadlines, including the
	15-day confirmation/access deadline of Article 19.
</p>
<p>
	<strong>13.2</strong> If the Processor receives a request directly from a comment author, it
	shall forward it to the Controller within 5 business days and shall not respond on the
	Controller's behalf unless instructed.
</p>

<h2 id="s14">14. Personal Data Incident Notification</h2>
<p>
	<strong>14.1</strong> The Processor shall notify the Controller without undue delay after
	becoming aware of a personal data incident affecting Comment Data or Moderation Outcome Data,
	providing the information reasonably available to enable the Controller to assess its own
	notification duties.
</p>
<p>
	<strong>14.2</strong> The Parties acknowledge that under ANPD Resolution CD/ANPD no 15/2024 a
	controller must notify the ANPD and affected data subjects within 3 business days of becoming
	aware of an incident that may entail relevant risk or harm. The Processor shall cooperate in
	good faith so the Controller can meet that deadline.
</p>

<h2 id="s15">15. Statutory Log Retention (Marco Civil da Internet)</h2>
<p>
	<strong>15.1</strong> Notwithstanding Section 7, the Processor retains connection records and
	records of access to applications for the statutory period of 6 months under Articles 13 and
	15 of the Marco Civil; these logs and the Moderation Outcome Data described in Section 7 are
	the only records the Processor retains.
</p>
<p>
	<strong>15.2</strong> Such logs are stored separately from operational data, kept under
	secrecy as required by law, used solely for legal compliance, and automatically and
	permanently deleted at the end of the statutory retention period.
</p>

<h2 id="s16">16. Audits and Compliance Documentation</h2>
<p>
	<strong>16.1</strong> The Processor shall make available, upon reasonable request,
	documentation demonstrating compliance with this DPA, including a summary of its RIPD, its
	security policies, and records of processing relevant to the Service.
</p>
<p>
	<strong>16.2</strong> Audits shall be conducted primarily through documentation and written
	questionnaires. On-site inspections are permitted at most once per year (or when required by
	the ANPD), with 30 days' notice, during business hours, at the Controller's reasonable cost,
	and subject to confidentiality.
</p>

<h2 id="s17">17. Term, Termination and Deletion</h2>
<p>
	<strong>17.1</strong> This DPA takes effect on the date the Controller accepts the
	<a href="/terms">Moderaty Terms of Service</a> or signs this DPA, whichever occurs first, and
	remains in force for the duration of the processing.
</p>
<p>
	<strong>17.2</strong> Upon termination of the Service, the Processor shall delete any
	remaining Comment Data within 30 days, except the statutory logs under Section 15, and shall
	certify the deletion upon the Controller's written request.
</p>

