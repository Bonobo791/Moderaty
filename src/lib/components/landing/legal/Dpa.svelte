<h2 id="annex-4">Annex IV — International Transfer Mechanism (ANPD Standard Contractual Clauses)</h2>
<p>
	<strong>IV.1</strong> For each international transfer of personal data under this DPA that
	relies on standard contractual clauses, the Parties incorporate by reference the standard
	contractual clauses approved by ANPD Resolution CD/ANPD no 19/2024 (ANPD SCCs), which apply
	in full and prevail over any conflicting term of this DPA in respect of the transfer.
</p>
<p>
	<strong>IV.2</strong> For transfers to sub-processors, the Processor acts as data exporter
	and the sub-processor as data importer, with the ANPD SCCs executed between them; the
	Processor shall provide the Controller copies upon request.
</p>
<p>
	<strong>IV.3</strong> Where a transfer relies on another Article 33 mechanism (for example,
	an ANPD adequacy decision), Annex III records that mechanism, and this Annex IV applies only
	to transfers recorded as relying on the ANPD SCCs.
</p>
<p>
	<strong>IV.4</strong> The Parties acknowledge that standard contractual clauses of other
	jurisdictions (including EU SCCs) do not satisfy Article 33 of the LGPD and shall not be used
	as a substitute for the ANPD SCCs.
</p>
