<h2 id="s7">7. Data Minimization and Author-Identifier Retention Limits</h2>
<p>
	<strong>7.1</strong> The Processor minimizes retained Comment Data: comments are retrieved,
	classified, and acted upon; comment text (truncated to 500 characters) is stored solely as
	part of Moderation Outcome Data. The commenter's public handle is stored with the record and
	shown in the activity log for up to 30 days, is then erased automatically, and may be erased
	by the Controller on demand at any time; all other author identifiers (display name, author
	channel identifier) are not persistently stored by the Service, and no author channel
	identifiers are retained.
</p>
<p>
	<strong>7.2</strong> Author identifiers other than the public handle are processed
	transiently, in memory only, strictly for the duration required to classify the comment and
	execute the configured moderation action, and are discarded immediately thereafter. The
	public handle is retained only as described in Clause 7.1.
</p>
<p>
	<strong>7.3</strong> Beyond the comment text stored within Moderation Outcome Data, the
	Processor shall not reconstruct, reassemble, or maintain archives of comment bodies or
	author profiles.
</p>
<p>
	<strong>7.4</strong> The Parties acknowledge that pseudonymized identifiers (such as hashed
	usernames) remain personal data under the LGPD. Other than the plain public handle retained
	under Clause 7.1, the Processor shall not retain author identifiers taken from Comment Data,
	pseudonymized or otherwise, and never for profiling or enrichment; it builds no pseudonymous
	profiles and performs no cross-service tracking of commenters. Channel identifiers and
	protected handles entered by the Controller in user rules are Controller configuration, not
	retained Comment Data.
</p>
<p>
	<strong>7.5</strong> The Processor shall not use Comment Data or Moderation Outcome Data to
	train, fine-tune, or improve machine-learning models, whether its own or third-party models.
</p>

<h2 id="s8">8. Sensitive Personal Data</h2>
<p>
	<strong>8.1</strong> The Parties acknowledge that Comment Data may incidentally contain
	sensitive personal data, including hate speech content that itself references race,
	ethnicity, religion, political opinion, health, or sexual orientation of data subjects or
	third parties.
</p>
<p>
	<strong>8.2</strong> The Processor's classification targets the abusive character of the
	content, not the personal traits of the author. The Processor shall not extract, profile,
	categorize, score, or enrich sensitive attributes of any data subject.
</p>
<p>
	<strong>8.3</strong> The lawful basis for the processing of sensitive personal data flows
	down from the Controller pursuant to Section 5, and the Processor acts on the Controller's
	instructions in that regard.
</p>

<h2 id="s9">9. Data of Children and Adolescents</h2>
<p>
	<strong>9.1</strong> The Parties acknowledge that Comment Data may include personal data
	authored by, or relating to, children or adolescents, and that the Processor cannot identify
	the age of comment authors and does not attempt to do so. Age assurance on the YouTube
	platform is the responsibility of the platform provider, not of the Parties.
</p>
<p>
	<strong>9.2</strong> Because age identification of comment authors is technically infeasible,
	the Processor treats all Comment Data to the highest protection standard, consistent with the
	best-interest principle of Article 14 of the LGPD and with the ECA Digital.
</p>
<p>
	<strong>9.3</strong> Accordingly, and without limiting Sections 7 and 8, the Processor shall
	not: (a) build or maintain profiles of comment authors; (b) perform author-level behavioral
	analysis or scoring (classification is content-level only); (c) use Comment Data for
	advertising or commercial profiling; or (d) use Comment Data for model training, as set out
	in Clause 7.5.
</p>
<p>
	<strong>9.4</strong> The Processor documents this design posture in its data protection
	impact assessment (RIPD) as the measure that satisfies the best-interest principle given the
	impossibility of age identification.
</p>

