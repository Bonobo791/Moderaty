<h2 id="s5">5. Controller Obligations and Lawful Basis</h2>
<p>
	<strong>5.1</strong> The Controller warrants that it has a valid lawful basis under Article 7
	of the LGPD for the processing of Comment Data and, to the extent Comment Data contains
	sensitive personal data within the meaning of Article 5, item II (for example, comment
	content revealing racial or ethnic origin, religious conviction, or political opinion), a
	valid basis under Article 11 of the LGPD.
</p>
<p>
	<strong>5.2</strong> The Parties note that legitimate interest (Article 7, item IX) is not an
	available basis for sensitive personal data under Article 11. The Parties anticipate that the
	relevant bases for sensitive data in this context will typically be: (a) compliance with a
	legal or regulatory obligation (Article 11, item II), including duties of care concerning
	gravely illicit content — such as hate speech and racism — as established by the Marco Civil
	and STF precedent; and/or (b) protection of the life or physical safety of the data subject
	or of a third party (Article 11, item VII).
</p>
<p>
	<strong>5.3</strong> The Controller is responsible for its own privacy notices to data
	subjects where required, for the lawfulness of its configuration choices in the Service, and
	for responding to data subject requests concerning Comment Data.
</p>
<p>
	<strong>5.4</strong> The Controller represents that it is at least 18 years of age, that the
	Service is a professional tool directed exclusively at adults, and that it is not a service
	likely or foreseeably accessed by children or adolescents within the meaning of the ECA
	Digital.
</p>

