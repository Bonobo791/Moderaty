<h2 id="s1">1. Purpose and Scope</h2>
<p>
	<strong>1.1</strong> This Data Processing Agreement (DPA) governs the processing of personal
	data by the Processor on behalf of the Controller in connection with Moderaty, a YouTube
	comment moderation service that retrieves comments from the Controller's YouTube channel(s)
	via the YouTube Data API, classifies them (including automated detection of hate speech and
	related abusive content), and executes moderation actions (such as holding, hiding, or
	removing comments) in accordance with the Controller's configuration of the Service.
</p>
<p>
	<strong>1.2</strong> This DPA applies to personal data of third-party comment authors
	contained in or associated with comments processed through the Service (Comment Data). The
	processing of the Controller's own account, contact, and billing data — for which the
	Processor acts as controller — is governed by the
	<a href="/terms">Moderaty Terms of Service</a> and <a href="/privacy">Privacy Policy</a>, not
	by this DPA.
</p>
<p>
	<strong>1.3</strong> The Parties acknowledge that the processing described in this DPA is
	carried out in Brazilian territory and is therefore subject to the LGPD pursuant to its
	Article 3, item I, regardless of the location of the Controller or of the data subjects.
</p>

<h2 id="s2">2. Definitions</h2>
<p>
	Capitalized terms not defined here have the meanings given in Article 5 of the LGPD,
	including: personal data; sensitive personal data; data subject; controller (controlador);
	operator/processor (operador); processing; anonymized data; and national authority (ANPD). In
	addition:
</p>
<ul>
	<li>
		<strong>(a)</strong> Comment Data: personal data contained in YouTube comments retrieved
		from the Controller's channel(s), including comment text, author display name or username,
		author channel identifier, and associated metadata.
	</li>
	<li>
		<strong>(b)</strong> Moderation Outcome Data: the minimal records the Processor retains
		after a moderation action, limited to the comment identifier reference, the comment text
		(truncated to 500 characters), the classification verdict, the action taken, the
		timestamp, and the commenter's public handle, which appears in the activity log for up
		to 30 days, is then erased automatically, and may be erased by the Controller on demand
		at any time. Moderation Outcome Data excludes all other author identifiers and author
		profile data.
	</li>
	<li>
		<strong>(c)</strong> ECA Digital: Law no 15.211/2025 (Digital Statute of Children and
		Adolescents), in force since March 2026.
	</li>
	<li>
		<strong>(d)</strong> Marco Civil: Law no 12.965/2014 (Brazilian Civil Rights Framework for
		the Internet), as interpreted by the Brazilian Supreme Court (STF) in its 2025 rulings on
		platform duties of care.
	</li>
	<li>
		<strong>(e)</strong> ANPD SCCs: the standard contractual clauses for international data
		transfers approved by ANPD Resolution CD/ANPD no 19/2024, mandatory for qualifying
		transfers since 23 August 2025.
	</li>
</ul>

<h2 id="s3">3. Roles of the Parties</h2>
<p>
	<strong>3.1</strong> The Controller is the controller of the Comment Data. The Processor is
	the operator (processor) and processes Comment Data solely on the Controller's documented
	instructions.
</p>
<p>
	<strong>3.2</strong> The Controller's documented instructions consist of: (a) this DPA; (b)
	the moderation rules, filters, thresholds, and actions the Controller configures in the
	Service; and (c) any written instruction issued through the Service or by e-mail. The
	Processor shall not process Comment Data for its own purposes.
</p>
<p>
	<strong>3.3</strong> If the Processor believes an instruction violates the LGPD or other
	applicable data protection law, it shall promptly inform the Controller and may suspend
	execution of the specific instruction until clarified.
</p>

